"""
release_info.py: Work out what kind of build this is and name it

Usage (from CI):
    python packaging/release_info.py <git-ref> <short-sha>

  refs/tags/v0.1.0           -> Stable release
  refs/tags/v0.1.0-beta.2    -> Pre-release (alpha / beta / rc)
  anything else              -> Nightly (artifacts only, never a GitHub release)

Writes ocmp/_version.py, release-notes.md, and KEY=VALUE lines to
$GITHUB_OUTPUT (version, channel, prerelease, is_release, title, tag, asset_prefix).
"""

import os
import re
import sys
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = "OpenCore Modernity Patcher"
ASSET = "OpenCore-Modernity-Patcher"

TAG_RE = re.compile(r"^v(?P<base>\d+\.\d+\.\d+)(?:-(?P<kind>alpha|beta|rc)\.(?P<num>\d+))?$")
KIND_LABEL = {"alpha": "Alpha", "beta": "Beta", "rc": "Release Candidate"}


def classify(ref: str, sha: str) -> dict:
    tag = ref[len("refs/tags/"):] if ref.startswith("refs/tags/") else ""
    m = TAG_RE.match(tag) if tag else None
    if tag and not m:
        raise SystemExit(f"Tag '{tag}' is not vX.Y.Z or vX.Y.Z-(alpha|beta|rc).N; refusing to release it.")

    codenames = json.loads((ROOT / "packaging" / "release_codenames.json").read_text())

    if m is None:
        base = _current_version().split("-")[0]
        version = f"{base}-nightly.{sha}"
        return dict(version=version, channel="Nightly", prerelease=False, is_release=False, tag="",
                    title=f"{APP} {version} (Nightly build, not released)", base=base,
                    codename=codenames.get(".".join(base.split(".")[:2]), ""))

    base, kind, num = m.group("base"), m.group("kind"), m.group("num")
    codename = codenames.get(".".join(base.split(".")[:2]), "")
    quoted = f' "{codename}"' if codename else ""
    if kind:
        version = f"{base}-{kind}.{num}"
        title = f"{APP} {base} {KIND_LABEL[kind]} {num}{quoted} (Pre-release)"
        channel = "Pre-release"
    else:
        version = base
        title = f"{APP} {base}{quoted}"
        channel = "Stable"
    return dict(version=version, channel=channel, prerelease=bool(kind), is_release=True, tag=tag,
                title=title, base=base, codename=codename)


def _current_version() -> str:
    text = (ROOT / "ocmp" / "_version.py").read_text()
    return re.search(r'VERSION = "([^"]+)"', text).group(1)


def changelog_section(version: str, base: str) -> str:
    """
    Text under '## [<version>]' (falls back to '## [<base>]') in CHANGELOG.md
    """
    text = (ROOT / "CHANGELOG.md").read_text()
    for wanted in (version, base):
        m = re.search(rf"^## \[{re.escape(wanted)}\][^\n]*\n(.*?)(?=^## \[|\Z)", text, re.M | re.S)
        if m:
            return m.group(1).strip()
    return "_No changelog entry for this version._"


def release_notes(info: dict) -> str:
    v = info["version"]
    exe = f"{ASSET}-{v}-Windows-x64.exe"
    appimage = f"{ASSET}-{v}-Linux-x86_64.AppImage"
    if not info["is_release"]:
        banner = ("> [!CAUTION]\n"
                  "> **Nightly build.** Built automatically from an untagged commit. Not a release, "
                  "not tested, for developers only.\n")
    elif info["prerelease"]:
        banner = ("> [!WARNING]\n"
                  "> **This is a pre-release.** It's for testing and may not boot your machine. "
                  "Keep a working EFI and a backup of your data. Report problems in Issues, "
                  "with your `BuildReport.txt` and the log from *File → Reveal Log File*.\n")
    else:
        banner = ("> [!NOTE]\n"
                  "> **Stable release.** Tested builds recommended for everyone. "
                  "Read the README's *Known limitations* before installing.\n")
    codename = f" · Codename **{info['codename']}**" if info["codename"] else ""
    return f"""{banner}
**Channel:** {info['channel']}{codename} · **Version:** `{v}`

## Downloads

| Platform | File | How to run |
|---|---|---|
| Windows 10/11 (x64) | `{exe}` | Double-click. For *Install OpenCore* and *Create macOS Installer*, right-click → **Run as administrator**. |
| Linux (x86_64, glibc 2.35+) | `{appimage}` | `chmod +x {appimage}` then run it. For disk steps: `sudo -E ./{appimage}` |

Verify downloads against `SHA256SUMS.txt`.

## What's changed

{changelog_section(v, info['base'])}

## Credits

This product includes software developed by Dortania and OpenCore Legacy Patcher contributors.
OpenCore, kexts and patches are downloaded at build time from their own projects. See the README's *Credits* section.
"""


def main() -> None:
    ref = sys.argv[1] if len(sys.argv) > 1 else ""
    sha = (sys.argv[2] if len(sys.argv) > 2 else "local")[:7]
    info = classify(ref, sha)

    (ROOT / "ocmp" / "_version.py").write_text(
        '"""\n_version.py: generated by packaging/release_info.py\n"""\n\n'
        f'VERSION = "{info["version"]}"\nCHANNEL = "{info["channel"]}"\nCOMMIT  = "{sha}"\n'
    )
    (ROOT / "release-notes.md").write_text(release_notes(info))

    outputs = {
        "version": info["version"], "channel": info["channel"], "prerelease": str(info["prerelease"]).lower(),
        "is_release": str(info["is_release"]).lower(), "title": info["title"], "tag": info["tag"],
        "asset_prefix": f"{ASSET}-{info['version']}",
    }
    for key, value in outputs.items():
        print(f"{key}={value}")
    if os.environ.get("GITHUB_OUTPUT"):
        with open(os.environ["GITHUB_OUTPUT"], "a") as f:
            for key, value in outputs.items():
                f.write(f"{key}={value}\n")


if __name__ == "__main__":
    main()
